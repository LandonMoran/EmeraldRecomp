#!/usr/bin/env python3
"""Generate the spoken map-name table from the decomp's map metadata.

The recompiled game carries no map names in guest memory - neither the map
header nor the layout has one - but the decomp's map_groups.json does, and it is
already imported as reference metadata. The player still deserves to hear where
they just walked into, so the names are compiled in here, keyed by the same
map group and number the game loads.

Usage: tools/gen_map_names.py [--check]
"""
import json
import re
import sys

FLOOR = re.compile(r"B?\d+F")

SOURCE = "third_party/pokeemerald/data/maps/map_groups.json"
OUTPUT = "src/accessibility/emerald_map_names.inc"

# Abbreviations the games use on screen, spelled out for the ear.
SPOKEN = {
    "Pokedex": "Pokédex",
    "Pokemon": "Pokémon",
    "Center": "Center",
    "1F": "1F",
    "2F": "2F",
    "B1F": "B1F",
}


def split_words(name: str) -> str:
    """MauvilleCity_PokemonCenter_1F -> 'Mauville City Pokémon Center'."""
    words = []
    for part in name.split("_"):
        word = ""
        for ch in part:
            if ch.isupper() and word and not word.isdigit():
                words.append(word)
                word = ch
            elif ch.isdigit() and word and not word[-1].isdigit():
                words.append(word)
                word = ch
            else:
                word += ch
        if word:
            words.append(word)
    # A floor number is detail a player asking "where am I" does not need: the
    # Centre's ground floor and its upstairs are the same building, so both are
    # announced as "Mauville City Pokémon Center".
    stripped = list(words)
    while stripped and FLOOR.fullmatch(stripped[-1]):
        stripped.pop()
    if not stripped:
        stripped = words   # a map named only by its floor keeps it
    return " ".join(SPOKEN.get(w, w) for w in stripped)


def main() -> int:
    data = json.load(open(SOURCE))
    order = data.get("group_order") or [k for k in data if k != "group_order"]
    rows = []
    for group, key in enumerate(order):
        for num, name in enumerate(data[key]):
            if name.startswith("MAP_"):
                continue
            rows.append((group, num, name, split_words(name)))
    rows.sort(key=lambda r: (r[0] << 8) | r[1])

    lines = [
        "// Generated by tools/gen_map_names.py from the decomp's map metadata.",
        "// Map group/number to the name a player would read on the town banner.",
        "// Do not edit by hand.",
        "static const MapNameEntry kMapNames[] = {",
    ]
    for group, num, raw, spoken in rows:
        lines.append(
            '    {%d, %d, "%s", "%s"},' % (group, num, raw, spoken.replace('"', '\\"')))
    lines.append("};")
    text = "\n".join(lines) + "\n"

    if "--check" in sys.argv:
        try:
            current = open(OUTPUT).read()
        except OSError:
            current = None
        if current != text:
            print("map names out of date: run tools/gen_map_names.py")
            return 1
        print("map names up to date (%d maps)" % len(rows))
        return 0

    open(OUTPUT, "w").write(text)
    print("wrote %s (%d maps)" % (OUTPUT, len(rows)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
