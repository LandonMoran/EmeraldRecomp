#!/usr/bin/env python3
"""Generate the accessibility cue sounds that ship with the app.

The ten original cues are Kenney's CC0 "Interface Sounds" pack. The four added
for signs, trainers, battles and menus are synthesized here instead, so their
provenance is unambiguous: they are original works, generated by this script
from sine/noise arithmetic, and dedicated to the public domain (CC0 1.0). There
is no third-party sample in them and no attribution obligation.

They are short, quiet and distinct from each other so a blind player can tell
"there is a sign in front of me" from "someone wants to battle":

    sign     a paper-ish rustle under a soft high chime   (something to read)
    trainer  two firm descending blips                    (someone noticed you)
    battle   a quick rising three-note sting              (a battle starts)
    menu     one tiny high click                          (a menu opened)

Requirements (generation only; the .ogg files are committed):
    pip install numpy soundfile

Run from the repository root:
    python3 tools/make_a11y_cues.py

Output: android/app/src/main/assets/a11y/sfx/{sign,trainer,battle,menu}.ogg,
44.1 kHz mono Ogg Vorbis, peak -6 dBFS.
"""

import os

import numpy as np
import soundfile as sf

SR = 44100
OUT_DIR = os.path.join("android", "app", "src", "main", "assets", "a11y", "sfx")
PEAK = 0.5          # -6 dBFS


def frames(seconds):
    return int(round(SR * seconds))


def envelope(n, attack=0.005, release=None):
    """Raised-cosine attack and release, so nothing starts or ends with a click."""
    env = np.ones(n)
    a = min(max(1, frames(attack)), n)
    env[:a] = 0.5 - 0.5 * np.cos(np.pi * np.arange(a) / a)
    r = min(max(1, frames(release if release is not None else 0.04)), n)
    env[-r:] *= 0.5 + 0.5 * np.cos(np.pi * np.arange(r) / r)
    return env


def tone(freq, seconds, start=0.0, total=None, decay=None, wave="sine"):
    """A single note placed at `start` inside a buffer of `total` seconds."""
    total = total if total is not None else seconds
    n = frames(total)
    out = np.zeros(n)
    s = frames(start)
    m = frames(seconds)
    t = np.arange(m) / SR
    if wave == "sine":
        x = np.sin(2 * np.pi * freq * t)
    elif wave == "triangle":
        x = 2 / np.pi * np.arcsin(np.sin(2 * np.pi * freq * t))
    else:  # soft square: odd harmonics, gentle on the ear
        x = np.sin(2 * np.pi * freq * t) + np.sin(2 * np.pi * freq * 3 * t) / 3.0
    if decay:
        x *= np.exp(-t / decay)
    x *= envelope(m, attack=0.004, release=0.03)
    end = min(n, s + m)
    out[s:end] += x[:end - s]
    return out


def noise_burst(seconds, seed, band=(1200.0, 5200.0)):
    """Rustle: white noise shaped into a narrow band, with a rising envelope."""
    rng = np.random.default_rng(seed)
    m = frames(seconds)
    x = rng.standard_normal(m)
    # Cheap band shaping: one-pole low-pass difference plus a moving average.
    lo = 1.0 - np.exp(-2 * np.pi * band[0] / SR)
    hi = 1.0 - np.exp(-2 * np.pi * band[1] / SR)
    lp = np.zeros(m)
    hp = np.zeros(m)
    acc = 0.0
    for i in range(m):
        acc += lo * (x[i] - acc)
        lp[i] = acc
    acc = 0.0
    for i in range(m):
        acc += hi * (lp[i] - acc)
        hp[i] = acc
    x = lp - hp
    t = np.arange(m) / SR
    x *= np.exp(-t / (seconds * 0.35))
    x *= envelope(m, attack=0.006, release=0.05)
    return x


def sign_cue():
    total = 0.30
    out = tone(1046.5, 0.16, start=0.03, total=total, decay=0.07) * 0.55   # C6
    out += tone(1568.0, 0.10, start=0.10, total=total, decay=0.05) * 0.30  # G6
    rustle = noise_burst(0.14, seed=7)
    s = frames(0.0)
    out[s:s + rustle.size] += rustle * 0.45
    return out


def trainer_cue():
    total = 0.26
    out = tone(783.99, 0.085, start=0.0, total=total, decay=0.10, wave="soft_square") * 0.6
    out += tone(523.25, 0.11, start=0.10, total=total, decay=0.11, wave="soft_square") * 0.6
    return out


def battle_cue():
    total = 0.32
    out = tone(523.25, 0.09, start=0.00, total=total, decay=0.09) * 0.55
    out += tone(659.25, 0.09, start=0.07, total=total, decay=0.09) * 0.55
    out += tone(783.99, 0.17, start=0.14, total=total, decay=0.10) * 0.60
    out += tone(1567.98, 0.14, start=0.15, total=total, decay=0.05) * 0.18
    return out


def menu_cue():
    total = 0.09
    out = tone(1318.5, 0.05, start=0.0, total=total, decay=0.03, wave="triangle") * 0.55
    out += tone(2637.0, 0.02, start=0.0, total=total, decay=0.01) * 0.12
    return out


CUES = {
    "sign": sign_cue,
    "trainer": trainer_cue,
    "battle": battle_cue,
    "menu": menu_cue,
}


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    for name, build in CUES.items():
        x = build()
        peak = float(np.max(np.abs(x)))
        if peak > 0:
            x = x * (PEAK / peak)
        path = os.path.join(OUT_DIR, name + ".ogg")
        sf.write(path, x.astype(np.float32), SR, format="OGG", subtype="VORBIS")
        print(f"{path}: {os.path.getsize(path)} bytes, {len(x) / SR:.2f}s")


if __name__ == "__main__":
    main()
